create table if not exists public.profiles (
  id uuid primary key,
  full_name text not null,
  phone text,
  email text not null unique,
  role public.user_role not null default 'CUSTOMER',
  created_at timestamptz not null default now()
);
create table if not exists public.ticket_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  price numeric(12,2) not null check (price >= 0),
  description text,
  active boolean not null default true
);
create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.profiles(id),
  amount numeric(12,2) not null check (amount >= 0),
  status text not null,
  reference text not null unique,
  paid_at timestamptz not null default now()
);
create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  code text not null unique,
  qr_token text not null unique,
  customer_id uuid not null references public.profiles(id),
  ticket_type_id bigint not null references public.ticket_types(id),
  payment_id bigint not null references public.payments(id),
  price numeric(12,2) not null,
  status public.ticket_status not null default 'VALID',
  purchased_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create table if not exists public.ticket_scans (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets(id),
  scanned_by_id uuid references public.profiles(id),
  scanned_at timestamptz not null default now(),
  result text not null
);
create index if not exists tickets_status_idx on public.tickets(status);
create index if not exists tickets_purchased_idx on public.tickets(purchased_at desc);

